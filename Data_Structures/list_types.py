# list_types.py

# List of friends' full names
friends_names = [
    "John Smith",
    "Sarah Johnson",
    "Michael Brown"
]

# Print the first friend's name
print(f"First friend: {friends_names[0]}")

# Print the last friend's name
print(f"Last friend: {friends_names[-1]}")

# Print the length of the list
print(f"Number of friends: {len(friends_names)}")

# List of friends' ages
friends_ages = [24, 25, 23]

# Print each friend's name and age
print(f"{friends_names[0]} is {friends_ages[0]} years old")
print(f"{friends_names[1]} is {friends_ages[1]} years old")
print(f"{friends_names[2]} is {friends_ages[2]} years old")